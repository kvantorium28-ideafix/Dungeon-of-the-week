SWORD_TIERS = [1, 6, 10]  # меч улучшается от уровня героя


def skill_level(xp: int) -> int:
    return sum(1 for t in SKILL_XP if xp >= t)


def skill_info(group: str, xp: int) -> dict:
    lvl = skill_level(xp)
    cur = SKILL_XP[lvl - 1]
    nxt = SKILL_XP[lvl] if lvl < len(SKILL_XP) else None
    return {
        "id": group, "name": GROUPS[group][0], "xp": xp, "level": lvl,
        "rank": SKILL_RANKS[lvl - 1],
        "progress": 1.0 if nxt is None else (xp - cur) / (nxt - cur),
        "to_next": None if nxt is None else nxt - xp,
    }


