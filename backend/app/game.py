def unlocked(items: list[dict], xp: int) -> list[dict]:
    lvl = level_for(xp)
    return [dict(item, unlocked=item["level"] <= lvl) for item in items]


def weapons_unlocked(skill_xp: dict[str, int], hero_level: int) -> list[dict]:
    # ступень оружия от 0 до 3. у меча считаем по уровню героя
    out = []
    for w in WEAPONS:
        if w["skill"] is None:
            lvl, steps, source = hero_level, SWORD_TIERS, "уровень героя"
        else:
            lvl, steps, source = skill_level(skill_xp.get(w["skill"], 0)), WEAPON_TIERS, GROUPS[w["skill"]][0]
        tier = sum(1 for t in steps if lvl >= t)
        nxt = None if tier == len(steps) else {"level": steps[tier], "name": w["names"][tier]}
        out.append({
            "id": w["id"], "skill": w["skill"], "tier": tier, "unlocked": tier > 0,
            "name": w["names"][max(tier, 1) - 1], "next": nxt, "source": source,
            "need": f"{source}: {steps[0]} уровень" if tier == 0 else "",
        })
    return out
