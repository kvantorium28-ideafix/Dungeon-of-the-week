def steps_for(kind: str, title: str, subject: str = "", trainings_possible: int = 3) -> list[tuple[str, bool]]:
    # список шагов: (название, это битва или нет)
    low = title.lower().replace("ё", "е")
    group = group_of(subject)

    if kind == "slime":
        return [(_pick(low, SLIME, "Сделать"), False)]

    if kind == "goblin":
        steps = _pick(low, GOBLIN_BY_KEY, None) or GOBLIN_BY_GROUP.get(group, GOBLIN_DEFAULT)
        return [(s, False) for s in steps]

    if kind == "troll":
        steps = _pick(low, TROLL, TROLL_DEFAULT)
        if "проект" in low and group in TROLL_PROJECT_BY_GROUP:
            steps = TROLL_PROJECT_BY_GROUP[group]
        return [(s, False) for s in steps]

    if kind == "guard":
        found = next(((tr, battle) for key, tr, battle in GUARD if key in low), GUARD_DEFAULT)
        trainings, battle = found
        return [(f"Тренировка: {s.lower()}", False) for s in trainings] + [(battle, True)]

    # у босса тренировок столько, сколько дней осталось (1-4)
    if "диктант" in low:
        trainings = BOSS_DICTATION
    elif any(k in low for k in ("пробн", "огэ", "егэ")):
        trainings = BOSS_EXAM
    else:
        trainings = BOSS_BY_GROUP.get(group, BOSS_DEFAULT)
    n = max(1, min(len(trainings), trainings_possible))
    battle = _pick(low, BOSS_BATTLE, "Битва: контрольная")
    return [(f"Тренировка: {s.lower()}", False) for s in trainings[:n]] + [(battle, True)]


